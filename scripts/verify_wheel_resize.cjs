// Regression: responsive height changes must not cancel a synchronized turn animation.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const timers = new Map();
let nextTimer = 0, observer, now = 0;
const classes = new Set();
const properties = new Map();
const style = () => ({setProperty(k,v){properties.set(k,v);}});
const slots = ['a','b','c'].map((id,rank)=>({dataset:{playerId:id,rank:String(rank)},figure:{style:{}},label:{style:{}},querySelector(s){return s==='.wheel-figure'?this.figure:this.label;}}));
const stage = {clientWidth:440,clientHeight:96,getBoundingClientRect(){return {height:this.clientHeight,width:this.clientWidth};}};
const root = {isConnected:true,dataset:{focusPlayer:'a',phase:'Action',depth:'1.3',duration:'1800',glow:'.35',originalColors:'80'},style:style(),classList:{add:c=>classes.add(c),remove:c=>classes.delete(c),contains:c=>classes.has(c)},querySelector:()=>stage,querySelectorAll:()=>slots,getBoundingClientRect:()=>({})};
const context = {performance:{now:()=>now},WeakMap,Map,Number,Math,Array,Boolean,ResizeObserver:class {constructor(cb){observer=cb;}observe(){}disconnect(){}},matchMedia:()=>({matches:false}),document:{visibilityState:'visible'},getComputedStyle:()=>({getPropertyValue:()=>76}),setTimeout:(fn,ms)=>{timers.set(++nextTimer,{fn,ms});return nextTimer;},clearTimeout:id=>timers.delete(id)};
const source = fs.readFileSync(path.join(__dirname,'../Ti4Companion.Web/wwwroot/prototype-initiative-wheel.js'),'utf8').replace(/export function /g,'function ');
vm.runInNewContext(source+';globalThis.api={update,disconnect};',context);
context.api.update(root);
root.dataset.focusPlayer='b';slots[0].dataset.rank='2';slots[1].dataset.rank='0';slots[2].dataset.rank='1';
context.api.update(root);
assert(classes.has('wheel-moving'),'real handoff starts animation');
assert.equal(timers.size,1,'one finish deadline per handoff');
const deadline=[...timers.keys()][0];
stage.clientHeight=50;
now=900;
observer();
assert.equal(properties.get('--wheel-duration'),'900ms','resize CSS transition must finish within remaining handoff time');
assert(classes.has('wheel-moving'),'responsive resize must preserve the live handoff animation');
assert(timers.has(deadline),'responsive resize must preserve the original animation deadline');
context.api.update(root);
assert.equal(timers.size,1,'duplicate server refresh must not replay animation');
timers.get(deadline).fn();
assert(!classes.has('wheel-moving'),'animation settles at original deadline');
stage.clientWidth=180;stage.clientHeight=250;observer();
assert.equal(root.dataset.wheelLayout,'vertical','narrow tall order zone must use its height');
assert.equal(slots[1].label.style.width,'172px','vertical queue must give player names the full zone width');
const y=slot=>Number(/translate\([^,]+,([^p]+)px\)/.exec(slot.label.style.transform)[1]);
assert(y(slots[1])<y(slots[2])&&y(slots[2])<y(slots[0]),'ranked names must run top to bottom');
assert(y(slots[0])+16<=stage.clientHeight,'last visible name must stay inside stage');
context.api.disconnect(root);
console.log('PASS: live handoff survives responsive stage resize, keeps original deadline, and does not replay on duplicate refresh');
